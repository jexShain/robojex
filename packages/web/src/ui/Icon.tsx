export type IconName = keyof typeof PATHS

export interface IconProps {
  name: IconName
  size?: number
  strokeWidth?: number
  className?: string
  style?: CSSProperties
}

/** Inline stroke icon. `name` is typed; an unknown name renders nothing. */
export function Icon({ name, size = 14, strokeWidth = 2, className, style }: IconProps): JSX.Element {
  const d = PATHS[name]
  if (!d) return <span className={className} style={style} data-icon-fallback={name} aria-hidden="true" />
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
      style={{ flex: 'none', ...style }}
      dangerouslySetInnerHTML={{ __html: d }}
    />
  )
}

/** Deterministic gear icon: the backend may still send an emoji field (older
 *  cores), but the UI never renders it — the id picks the glyph. */
export function gearIcon(id: string): IconName {
  switch (id) {
    case 'dormant': return 'moon'
    case 'eco': return 'leaf'
    case 'balanced': return 'scale'
    case 'focused': return 'target'
    case 'turbo': return 'rocket'
    default: return 'gauge'
  }
}

/** Verdict glyph: pass → check, fail → x, partial → half-filled circle. */
export function verdictIcon(verdict: string): IconName {
  switch (verdict) {
    case 'pass': return 'check'
    case 'fail': return 'x'
    case 'partial': return 'partial'
    default: return 'clock'
  }
}
